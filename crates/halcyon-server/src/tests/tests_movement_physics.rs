#[test]
fn owner_driven_ground_trajectories_match_the_target_client() {
    for &(id, mode, expected) in REFERENCE {
        let plane = Plane(id, mode);
        let height =
            state_info(id).collision_boxes().iter().map(|shape| shape.max[1]).fold(0.0, f64::max);
        let falling = mode == "fall";
        let mut state = MovementState::new(Transform {
            x: 0.5,
            y: if falling { 5.0 } else { height },
            z: 0.5,
            on_ground: !falling,
            ..Default::default()
        });
        let steps = if falling {
            14
        } else if mode == "edge" {
            20
        } else {
            8
        };
        for tick in 0..steps {
            let input = GroundInput {
                forward: !falling && !(mode == "stop" && tick >= 4),
                jumping: matches!(mode, "jump" | "sprint_jump" | "ceiling") && tick == 0,
                sprinting: matches!(mode, "sprint" | "sprint_jump"),
                left: mode == "diagonal",
                yaw: if mode == "diagonal" { 37.0 } else { 0.0 },
                sneaking: matches!(mode, "sneak" | "edge"),
                ..Default::default()
            };
            let result = state.step_with(&plane, input);
            assert!(!result.correction, "state={id} {mode} tick={tick}: {result:?}");
            assert!(result.collision_cells <= CELLS_PER_STEP);
        }
        let transform = state.transform();
        let velocity = state.motion.velocity;
        let actual = [transform.x, transform.y, transform.z, velocity[0], velocity[1], velocity[2]];
        for (actual, expected) in actual.into_iter().zip(expected) {
            assert!(
                (actual - expected).abs() < 2e-9,
                "state={id} {mode}: actual={actual} expected={expected}"
            );
        }
    }
}

#[test]
fn landing_modifiers_honey_slides_and_sneak_suppression_are_shared() {
    assert_eq!(landing_damage(10.0, MotionInfo::default(), false), 7.0);
    assert_eq!(landing_damage(10.0, motion_info(14379), false), 0.0);
    assert_eq!(landing_damage(10.0, motion_info(14379), true), 7.0);
    assert_eq!(landing_damage(10.0, motion_info(2030), false), 2.0);
    assert_eq!(landing_damage(10.0, motion_info(25173), false), 2.0);
    let mut state = MovementState::new(Transform { x: 0.5, y: 5.0, z: 0.5, ..Default::default() });
    let mut damage = None;
    for _ in 0..14 {
        let result = state
            .step_with(&Plane(14379, ""), GroundInput { sneaking: true, ..Default::default() });
        damage = result.landed_fall_damage.or(damage);
    }
    assert_eq!(damage, Some(1.0));
    assert_eq!(state.transform().y, 1.0);
    assert!(state.motion.velocity[1] < 0.0);
    let mut map = super::super::tests::Map::floor();
    for y in 0..=3 {
        map.blocks.insert((0, y, 0), (state_info(25173).collision_boxes(), false));
        map.surfaces.insert((0, y, 0), motion_info(25173));
    }
    state.reset(Transform { x: 1.24, y: 3.0, z: 0.5, ..Default::default() });
    state.motion.velocity[1] = -0.5;
    let result = state.step_with(&map, GroundInput::default());
    assert!(!result.correction);
    assert!((state.motion.velocity[1] - (-0.13 * AIR_DRAG)).abs() < 1e-12);
    assert_eq!(state.fall_distance, 0.0);
}
