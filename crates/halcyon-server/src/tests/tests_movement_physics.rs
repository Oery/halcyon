use super::*;

struct Plane<'a>(u16, &'a str);
impl Terrain for Plane<'_> {
    fn contains_column(&self, _: i32, _: i32) -> bool {
        true
    }
    fn cell(&self, _: i32, y: i32, z: i32) -> Option<TerrainCell> {
        let id = match (self.1, y, z) {
            ("edge", _, z) if z != 0 => return None,
            ("wall", 1, 1) | ("ceiling", 3, _) => 1,
            ("step", 1, 1) => 15252,
            ("stair", 1, 1) => 19144,
            (_, 0, _) => self.0,
            _ => return None,
        };
        Some(TerrainCell {
            shapes: state_info(id).collision_boxes(),
            uncertain: false,
            contextual: false,
            motion: motion_info(id),
        })
    }
}

